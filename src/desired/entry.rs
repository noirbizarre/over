use std::path::{Path, PathBuf};
use std::sync::Arc;

use crate::actions::git::config::GitRepoConfig;
use crate::actions::symlink::LinkType;
use crate::overlays::FileMode;
use crate::overlays::ignore::SourcePolicy;

/// Source routing holes and optional positive destination-leaf ownership.
#[derive(Debug, Clone, Default, serde::Deserialize, serde::Serialize)]
pub struct CheckoutScope {
    /// Desired leaves are runtime inputs, not a second snapshot store in XDG.
    #[serde(skip)]
    pub rendered: Option<Arc<super::content::RenderedCheckout>>,
    pub source_excludes: Vec<PathBuf>,
    pub target_excludes: Vec<PathBuf>,
    /// Positive leaf ownership for fresh checkouts; absence preserves legacy exclusivity.
    /// Box the inventory header to keep intents and paired migration operations compact.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub projection: Option<Box<std::collections::BTreeSet<PathBuf>>>,
    /// Current source selection is runtime policy, never persisted ownership.
    #[serde(skip)]
    pub source_policy: Option<(PathBuf, Arc<SourcePolicy>)>,
}

impl PartialEq for CheckoutScope {
    fn eq(&self, other: &Self) -> bool {
        // Editing ignore rules must not invalidate an existing checkout association.
        self.source_excludes == other.source_excludes
            && self.target_excludes == other.target_excludes
            && self.projection.is_some() == other.projection.is_some()
    }
}

impl Eq for CheckoutScope {}

impl CheckoutScope {
    pub fn owns_source(&self, path: &Path) -> bool {
        self.owns_source_kind(path, false)
    }

    pub fn owns_source_kind(&self, path: &Path, is_dir: bool) -> bool {
        self.selects(path, is_dir)
            && !self.rendered.as_ref().is_some_and(|inventory| {
                self.source_policy.as_ref().is_some_and(|(root, _)| {
                    inventory
                        .values()
                        .any(|file| file.generated && file.source == root.join(path))
                })
            })
            && !self
                .source_excludes
                .iter()
                .any(|root| path.starts_with(root))
    }

    pub fn owns_target(&self, path: &Path) -> bool {
        self.owns_target_kind(path, false)
    }

    pub fn owns_target_kind(&self, path: &Path, is_dir: bool) -> bool {
        (self.rendered.is_some() || self.selects(path, is_dir))
            && self.projection.as_ref().is_none_or(|paths| {
                if is_dir {
                    // Ordered prefixes avoid scanning the inventory for every shared directory.
                    paths
                        .range(path.to_path_buf()..)
                        .next()
                        .is_some_and(|leaf| leaf.starts_with(path))
                } else {
                    paths.contains(path)
                }
            })
            && !self
                .target_excludes
                .iter()
                .any(|root| path.starts_with(root))
    }

    fn selects(&self, path: &Path, is_dir: bool) -> bool {
        self.source_policy
            .as_ref()
            .is_none_or(|(source, policy)| policy.includes(&source.join(path), is_dir))
    }
}

/// What kind of filesystem node a [`DesiredEntry`] should be, independent of
/// *how* it gets there (see [`MaterializationIntent`]).
///
/// `File` represents partial blocks and decrypted whole files. Rendered
/// symlink-mode files expose generated artifacts; encrypted entries carry
/// recipes rather than plaintext so plans and diagnostics cannot disclose it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EntryKind {
    Directory,
    File,
    Symlink,
}

/// How a [`DesiredEntry`] is (or will be) turned into a real filesystem node.
///
/// Distinct from [`EntryKind`]: this is the resolved strategy/rule that
/// produced the entry, not just the node type it results in. Keeping the two
/// separate matters for #113's later migration detection (e.g. detecting a
/// `SymlinkDirectory -> Checkout` rule change as an explicit transition
/// rather than an implicit delete/recreate).
#[derive(Debug, Clone)]
pub enum MaterializationIntent {
    /// Generated bytes and original source identity; exposed through an XDG artifact link.
    RenderedFile(Arc<super::content::RenderedFile>),
    /// A plaintext-free recipe; content is authenticated only when needed.
    EncryptedFile(crate::secrets::EncryptedFile),
    /// Plain `mkdir` for a directory scaffold.
    Directory,
    /// Symlink a single file from `source` (file-level materialization).
    SymlinkFile {
        source: PathBuf,
        link_type: LinkType,
    },
    /// Symlink a whole directory from `source` as one unit
    /// (a mode rule, or a `.link.*` sidecar resolving to a directory).
    SymlinkDirectory {
        source: PathBuf,
        link_type: LinkType,
    },
    /// A Git-managed path (`overlay.git`). Materialized by
    /// [`crate::materialize::CheckoutMaterializer`] (#110): ensures the
    /// repository/worktree is present and configured, the same "presence"
    /// concern `actions::git::clone_repositories` already implements.
    /// Manage its content with ordinary Git. The CLI's `over sync` reconciles
    /// local virtual checkouts, not these declared repositories; the broader
    /// [`crate::sync`] library API remains separate from materialization.
    Checkout,
    /// A subtree materialized as a virtual checkout (#141,
    /// `MaterializationKind::Checkout` in `overlays::rules`): ordinary,
    /// directly editable files at the target, with **no** `.git` there —
    /// backed by the overlay's own source repository instead of a
    /// separately declared/cloned one. Unrelated to [`Self::Checkout`]
    /// above (see its doc and ADR-022 for the distinction). Materialized by
    /// `crate::materialize::virtual_checkout::VirtualCheckoutMaterializer`;
    /// content reconciliation (`over status`/`over diff`/`over commit`/
    /// `over sync`) is computed by comparing on-disk blob hashes against
    /// the overlay's own repository, never via a real git index at the
    /// target.
    VirtualCheckout,
    /// A checkout with routing policy and, for fresh deployments, projected leaves.
    /// The unscoped variant retains legacy exclusive ownership.
    ScopedVirtualCheckout(CheckoutScope),
    /// A managed block injected into an existing (possibly foreign) file,
    /// delimited by marker lines unique to `marker` (#66). The first intent
    /// to ever produce [`EntryKind::File`]: unlike every other intent, the
    /// target isn't replaced wholesale — only the delimited region is
    /// written/compared, so unrelated content in the same file is never
    /// touched. `content` is used verbatim (no template rendering — that's
    /// #61's job, kept independent per #66's own scope).
    PartialFile { content: String, marker: String },
}

impl MaterializationIntent {
    pub fn is_virtual_checkout(&self) -> bool {
        matches!(self, Self::VirtualCheckout | Self::ScopedVirtualCheckout(_))
    }

    pub fn checkout_scope(&self) -> CheckoutScope {
        match self {
            Self::ScopedVirtualCheckout(scope) => scope.clone(),
            _ => CheckoutScope::default(),
        }
    }

    /// The [`EntryKind`] this intent results in on disk.
    pub fn kind(&self) -> EntryKind {
        match self {
            MaterializationIntent::Directory
            | MaterializationIntent::Checkout
            | MaterializationIntent::VirtualCheckout
            | MaterializationIntent::ScopedVirtualCheckout(_) => EntryKind::Directory,
            MaterializationIntent::SymlinkFile { .. }
            | MaterializationIntent::RenderedFile(_)
            | MaterializationIntent::SymlinkDirectory { .. } => EntryKind::Symlink,
            MaterializationIntent::PartialFile { .. } | MaterializationIntent::EncryptedFile(_) => {
                EntryKind::File
            }
        }
    }
}

/// Where a [`DesiredEntry`] comes from, for reconciliation diagnostics.
#[derive(Debug, Clone)]
pub enum Provenance {
    /// A file/directory tracked directly in the overlay's own tree.
    Overlay { overlay: String, source: PathBuf },
    /// A `*.link.{toml,yaml,yml}` sidecar declaring an arbitrary symlink.
    ///
    /// Carries both the raw (pre-render) template and its resolved result —
    /// the "template provenance/rendering information" called for by #107.
    SymlinkSidecar {
        overlay: String,
        config: PathBuf,
        template: String,
        resolved: PathBuf,
    },
    /// A path backed by a Git repository/worktree declared on the overlay
    /// (`overlay.git`). Carries the repo config for "source
    /// repository/revision" diagnostics.
    ///
    /// Boxed: `GitRepoConfig` is comparatively large (worktrees/remotes/git
    /// config maps), and this variant would otherwise dominate the size of
    /// every `Provenance` value, most of which never carry one.
    Git {
        overlay: String,
        repo_key: String,
        config: Box<GitRepoConfig>,
    },
    /// A `*.partial.{toml,yaml,yml}` sidecar declaring a managed block
    /// injected into an external file (#66).
    PartialSidecar { overlay: String, config: PathBuf },
}

/// A single desired filesystem node — the canonical unit [`super::DesiredTree`]
/// is made of.
///
/// Generated content and provenance live in the rendered intent or checkout leaf
/// inventory, independently of tracked source files.
#[derive(Debug, Clone)]
pub struct DesiredEntry {
    /// Absolute path this entry should exist at.
    pub target: PathBuf,
    pub provenance: Provenance,
    pub intent: MaterializationIntent,
    /// Desired permissions resolved from scalar baselines and shared rules —
    /// see [`crate::overlays::Overlay::permission_for`].
    /// Used by partial files, encrypted whole files, and rendered artifacts.
    /// Generated checkout leaves carry their assignments in the rendered inventory.
    /// Ordinary source links cannot set independent permissions without mutating
    /// the source; scaffolds and ordinary checkouts have no assignment here.
    pub permissions: Option<FileMode>,
}

impl DesiredEntry {
    /// The [`EntryKind`] this entry should have once materialized.
    pub fn kind(&self) -> EntryKind {
        self.intent.kind()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn directory_intent_kind_is_directory() {
        assert_eq!(
            MaterializationIntent::Directory.kind(),
            EntryKind::Directory
        );
    }

    #[test]
    fn checkout_intent_kind_is_directory() {
        assert_eq!(MaterializationIntent::Checkout.kind(), EntryKind::Directory);
    }

    #[test]
    fn virtual_checkout_intent_kind_is_directory() {
        assert_eq!(
            MaterializationIntent::VirtualCheckout.kind(),
            EntryKind::Directory
        );
    }

    #[test]
    fn symlink_file_intent_kind_is_symlink() {
        let intent = MaterializationIntent::SymlinkFile {
            source: PathBuf::from("/src/file.txt"),
            link_type: LinkType::Soft,
        };
        assert_eq!(intent.kind(), EntryKind::Symlink);
    }

    #[test]
    fn partial_file_intent_kind_is_file() {
        let intent = MaterializationIntent::PartialFile {
            content: "alias ll='ls -la'".to_string(),
            marker: "aliases".to_string(),
        };
        assert_eq!(intent.kind(), EntryKind::File);
    }

    #[test]
    fn symlink_directory_intent_kind_is_symlink() {
        let intent = MaterializationIntent::SymlinkDirectory {
            source: PathBuf::from("/src/dir"),
            link_type: LinkType::Hard,
        };
        assert_eq!(intent.kind(), EntryKind::Symlink);
    }

    #[test]
    fn desired_entry_kind_delegates_to_intent() {
        let entry = DesiredEntry {
            target: PathBuf::from("/target/file.txt"),
            provenance: Provenance::Overlay {
                overlay: "ov".to_string(),
                source: PathBuf::from("/overlay/file.txt"),
            },
            intent: MaterializationIntent::SymlinkFile {
                source: PathBuf::from("/overlay/file.txt"),
                link_type: LinkType::Soft,
            },
            permissions: None,
        };
        assert_eq!(entry.kind(), EntryKind::Symlink);
    }
}
